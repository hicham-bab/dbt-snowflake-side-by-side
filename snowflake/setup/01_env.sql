-- =============================================================================
-- 01_env.sql  (dbt Projects on Snowflake side)
-- Roles, databases and grants for dev and prod. Every new dbt project, team or
-- developer means revisiting this file. Run as SECURITYADMIN + SYSADMIN.
-- Based on: docs.snowflake.com/en/user-guide/tutorials/dbt-projects-on-snowflake-ci-cd-tutorial
-- =============================================================================

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS ATLAS_SNOW_DEV_ROLE  COMMENT = 'Developers: build in ATLAS_SNOW_DEV';
CREATE ROLE IF NOT EXISTS ATLAS_SNOW_PROD_ROLE COMMENT = 'Prod deployments and tasks';
GRANT ROLE ATLAS_SNOW_DEV_ROLE  TO ROLE SYSADMIN;
GRANT ROLE ATLAS_SNOW_PROD_ROLE TO ROLE SYSADMIN;

-- Who gets which role is the real guardrail on this side.
-- A "team lead" who is granted ATLAS_SNOW_PROD_ROLE can run any workspace
-- straight into prod. Replace <DEMO_USER> with your user.
GRANT ROLE ATLAS_SNOW_DEV_ROLE  TO USER <DEMO_USER>;
GRANT ROLE ATLAS_SNOW_PROD_ROLE TO USER <DEMO_USER>;   -- intentional, for the guardrails beat

USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS ATLAS_SNOW_DEV;
CREATE DATABASE IF NOT EXISTS ATLAS_SNOW_PROD;
CREATE SCHEMA   IF NOT EXISTS ATLAS_SNOW_PROD.DBT_OBJECTS COMMENT = 'Deployed dbt project objects';
CREATE SCHEMA   IF NOT EXISTS ATLAS_SNOW_DEV.DBT_OBJECTS;

GRANT USAGE ON WAREHOUSE ATLAS_WH TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT USAGE ON WAREHOUSE ATLAS_WH TO ROLE ATLAS_SNOW_PROD_ROLE;

-- Shared raw data (setup/00_shared_raw.sql), read-only for both roles
GRANT USAGE ON DATABASE ATLAS_RAW TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT USAGE ON DATABASE ATLAS_RAW TO ROLE ATLAS_SNOW_PROD_ROLE;
GRANT USAGE ON SCHEMA ATLAS_RAW.ECOMMERCE TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT USAGE ON SCHEMA ATLAS_RAW.ECOMMERCE TO ROLE ATLAS_SNOW_PROD_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA ATLAS_RAW.ECOMMERCE TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA ATLAS_RAW.ECOMMERCE TO ROLE ATLAS_SNOW_PROD_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ATLAS_RAW.ECOMMERCE TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ATLAS_RAW.ECOMMERCE TO ROLE ATLAS_SNOW_PROD_ROLE;

-- Dev: developers own the dev database (dbt creates schemas on the fly)
GRANT ALL ON DATABASE ATLAS_SNOW_DEV TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT ALL ON SCHEMA ATLAS_SNOW_DEV.DBT_OBJECTS TO ROLE ATLAS_SNOW_DEV_ROLE;

-- Prod: deployment role owns prod
GRANT ALL ON DATABASE ATLAS_SNOW_PROD TO ROLE ATLAS_SNOW_PROD_ROLE;
GRANT ALL ON SCHEMA ATLAS_SNOW_PROD.DBT_OBJECTS TO ROLE ATLAS_SNOW_PROD_ROLE;
GRANT CREATE DBT PROJECT ON SCHEMA ATLAS_SNOW_PROD.DBT_OBJECTS TO ROLE ATLAS_SNOW_PROD_ROLE;
GRANT CREATE DBT PROJECT ON SCHEMA ATLAS_SNOW_DEV.DBT_OBJECTS  TO ROLE ATLAS_SNOW_DEV_ROLE;

-- Developers need to read prod to defer to it (Workspaces "Defer to Production")
GRANT USAGE ON DATABASE ATLAS_SNOW_PROD TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ATLAS_SNOW_PROD TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ATLAS_SNOW_PROD TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT SELECT ON ALL TABLES IN DATABASE ATLAS_SNOW_PROD TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT SELECT ON FUTURE TABLES IN DATABASE ATLAS_SNOW_PROD TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT SELECT ON ALL VIEWS IN DATABASE ATLAS_SNOW_PROD TO ROLE ATLAS_SNOW_DEV_ROLE;
GRANT SELECT ON FUTURE VIEWS IN DATABASE ATLAS_SNOW_PROD TO ROLE ATLAS_SNOW_DEV_ROLE;
-- ...and MONITOR on each prod dbt project object, after it exists (see 04_ci_cd_oidc.sql)

-- Tasks (05_tasks.sql) run as the prod role
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE ATLAS_SNOW_PROD_ROLE;
